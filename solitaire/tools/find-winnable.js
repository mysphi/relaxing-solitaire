// Builds src/winnable.js: lists of deals (shuffle seeds) proven winnable in
// Draw 1 and Draw 3. Run with: node tools/find-winnable.js [count]
// Each deal is kept only if the solver finds a winning line AND that line
// replays to a win through the real rules in engine.js.

import { writeFileSync } from 'node:fs';
import { isWon, mulberry32 } from '../src/engine.js';
import { solveSeed, replay } from '../src/solver.js';

const COUNT = Number(process.argv[2] || 1000);
const rand = mulberry32(20261024);

function find(drawCount) {
  const found = [];
  let tried = 0;
  while (found.length < COUNT) {
    const seed = Math.floor(rand() * 4294967296);
    tried++;
    const path = solveSeed(seed, drawCount, { limit: 150000 });
    if (!path) continue;
    const end = replay(seed, drawCount, path);
    if (end && isWon(end)) found.push(seed);
  }
  console.log(`Draw ${drawCount}: ${found.length} winnable from ${tried} tried`);
  return found;
}

const one = find(1);
const three = find(3);
writeFileSync(new URL('../src/winnable.js', import.meta.url),
  '// Generated by tools/find-winnable.js. Every seed here has a checked winning line.\n' +
  `export const DRAW1 = ${JSON.stringify(one)};\n` +
  `export const DRAW3 = ${JSON.stringify(three)};\n`);
